def _normalize_name(name: str) -> str:
    """Lowercase, strip whitespace, and replace hyphens/spaces with underscores.

    Args:
        name: Raw column or field name.

    Returns:
        Normalized string suitable for set-membership lookups.
    """
    return name.strip().lower().replace("-", "_").replace(" ", "_")


def _match_column_to_pi_category(
    column_name: str,
    column_type: str,
) -> Optional[str]:
    """Map a dataset column to a CCPA personal-information category.

    The lookup is performed against the pre-computed ``_PI_CATEGORY_LOOKUP``
    sets using the normalized column name.  If no exact match is found, a
    substring search is attempted against all registered PI field tokens.

    Args:
        column_name: The dataset column name.
        column_type: The declared data type of the column (e.g. ``'string'``).

    Returns:
        The CCPA PI category name (e.g. ``'identifiers'``) if matched,
        otherwise ``None``.
    """
    normalized = _normalize_name(column_name)

    # Exact match pass
    for category, field_set in _PI_CATEGORY_LOOKUP.items():
        if normalized in field_set:
            return category

    # Substring/contains pass — check if any PI field token is a substring
    # of the column name or vice-versa.
    for category, field_set in _PI_CATEGORY_LOOKUP.items():
        for pi_field in field_set:
            if pi_field in normalized or normalized in pi_field:
                return category

    # Type-hint heuristic: certain column types hint at PI regardless of name
    col_type_lower = column_type.lower() if column_type else ""
    type_category_map: Dict[str, str] = {
        "email": "identifiers",
        "ip_address": "identifiers",
        "ip": "identifiers",
        "ssn": "identifiers",
        "phone": "identifiers",
        "geolocation": "geolocation_data",
        "gps": "geolocation_data",
        "biometric": "biometric_information",
        "url": "internet_activity",
    }
    for type_hint, cat in type_category_map.items():
        if type_hint in col_type_lower:
            return cat

    return None


def _is_sensitive_pi(pi_category: str, column_name: str) -> bool:
    """Determine whether a PI match qualifies as *sensitive* under CPRA.

    Sensitive personal information is defined in Cal. Civ. Code §1798.140(ae)
    and includes government-issued IDs, financial credentials, precise
    geolocation, racial/ethnic origin, genetic data, biometric data, health
    data, sex-life/orientation, and contents of personal communications.

    Args:
        pi_category: The CCPA PI category (e.g. ``'identifiers'``).
        column_name: The original (non-normalized) column name.

    Returns:
        ``True`` if the field is classified as sensitive PI, ``False`` otherwise.
    """
    normalized = _normalize_name(column_name)

    # Direct field-level check
    if normalized in _SENSITIVE_PI_FIELDS:
        return True

    # Category-level check: certain entire categories are sensitive
    if pi_category in _SENSITIVE_PI_CATEGORIES:
        # For identifiers, only government IDs and SSN are sensitive —
        # not all identifiers qualify.
        if pi_category == "identifiers":
            gov_ids = {
                "ssn",
                "social_security_number",
                "drivers_license",
                "passport_number",
                "state_id",
            }
            return normalized in gov_ids
        return True

    # Substring heuristic for fields not in the exact set
    for sensitive_token in _SENSITIVE_PI_FIELDS:
        if sensitive_token in normalized or normalized in sensitive_token:
            return True

    return False


