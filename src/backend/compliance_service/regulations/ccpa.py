"""CCPA (California Consumer Privacy Act) compliance rules and verification.

This module implements CCPA regulatory compliance verification for synthetic
datasets generated by the Synthetic ERP Data Generation Platform.  It checks
generated data against the personal information categories defined in
Cal. Civ. Code §1798.140(o), validates consumer rights compliance, and
enforces CPRA (California Privacy Rights Act) amendments for sensitive
personal information.

The :class:`CCPARegulationChecker` extends :class:`BaseRegulationChecker` and
is automatically registered in the :class:`RegulationRegistry` during package
import, enabling dynamic selection by the Compliance Service orchestration
layer.

Key compliance areas verified:

* **Personal Information Categories** — 9 categories per §1798.140(o)
* **Sensitive Personal Information** — CPRA §1798.140(ae)
* **Consumer Rights** — right to know, delete, opt-out, non-discrimination,
  correct, and limit use of sensitive PI
* **Data Sale Provisions** — §1798.120 opt-out and notice requirements
* **Minors Consent** — §1798.120(c)-(d) parental/opt-in requirements

Typical usage::

    from compliance_service.regulations.ccpa import CCPARegulationChecker

    checker = CCPARegulationChecker()
    result = checker.check_compliance(dataset_metadata, scan_results)
    if not result.is_compliant:
        for v in result.violations:
            print(f"[{v.severity.value}] {v.description}")
"""

